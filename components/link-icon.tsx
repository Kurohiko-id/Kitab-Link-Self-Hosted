// Render icon dari value tersimpan (`links.icon`). Return null kalau value null/gak valid
// (caller biasanya fallback ke favicon auto-detect di kasus itu).
export function LinkIconRenderer({ value, className }: { value: string | null; className?: string }) {
  const parsed = parseIconValue(value);
  if (!parsed) return null;

  if (parsed.kind === "brand") {
    const brand = BRAND_ICONS[parsed.id as keyof typeof BRAND_ICONS];
    return (
      <svg role="img" viewBox="0 0 24 24" className={className} fill="currentColor">
        <title>{brand.title}</title>
        <path d={brand.path} />
      </svg>
    );
  }

  if (parsed.kind === "emoji") {
    return (
      <span
        className={cn("inline-flex shrink-0 items-center justify-center leading-none", className)}
        style={{ fontSize: emojiFontSizePx(className) }}
      >
        {parsed.id}
      </span>
    );
  }

  const Comp = GENERIC_COMPONENTS[parsed.id as GenericIconId];
  return Comp ? <Comp className={className} /> : null;
}

// className pemanggil biasanya ngatur ukuran SVG (Tailwind "size-4" dst = width/height).
// Emoji dirender sebagai teks biasa, bukan svg, jadi ukurannya butuh font-size eksplisit --
// diturunin dari angka size-N yang sama biar tetep sepadan sama icon svg di sebelahnya.
function emojiFontSizePx(className?: string): string {
  const match = className?.match(/size-(\d+(?:\.\d+)?)/);
  const n = match ? Number(match[1]) : 4;
  return `${Math.round(n * 4 * 0.85)}px`;
}

